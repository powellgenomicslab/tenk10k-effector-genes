# Read in coloc result 
# (preprocess_results.R also defines df_coloc and df_mvcoloc; the block below is kept as in the
# original Crohn's analysis and overrides them, copied from workflow/rules/snakescripts/preprocess/tenk10k_phase1.v5.R)
# # coloc - v3: rebuilt 2026-08-13 after fixing the aggregation reader and
# re-running coloc for the 34 traits whose GWAS carried zero-SE or duplicate-ID
# SNPs. See CHANGELOG.v5.md.
df_coloc <- read_parquet("results/aggregate/coloc/tenk10k_phase1.coloc.v3.parquet.gz") %>%
  mutate(across(c(PP.H0.abf:PP.H4.abf), as.numeric)) %>%
  mutate(pp_h3_h4 = PP.H3.abf + PP.H4.abf,
         sig = PP.H4.abf >= 0.8) %>%
  filter(pheno %in% phenotypes, gene %in% gene_universe)

# multivariant coloc
df_mvcoloc <- read_parquet("results/aggregate/coloc/tenk10k_phase1.mvcoloc.parquet.gz") |> 
  filter(pheno %in% phenotypes, gene %in% gene_universe) |> 
  mutate(across(c(PP.H0.abf:PP.H4.abf), as.numeric)) |> 
  mutate(pp_h3_h4 = PP.H3.abf + PP.H4.abf) |> 
  # take maximum PP.H4.abf per gene-phenotype-biosample combination
  group_by(gene, pheno, biosample) |>
  arrange(desc(PP.H4.abf), .by_group = TRUE) |> 
  slice_head(n = 1) |> 
  setDT()

# Save df_coloc 
df_coloc <- df_coloc %>% rename("probeID" = gene)
df_coloc <- df_coloc %>%
    left_join(df_gene_annot %>% select(hgnc_symbol, ensembl_gene_id), by = c("probeID" = "ensembl_gene_id")) %>%
    rename(Gene = hgnc_symbol)

saveRDS(df_coloc, paste0(crohns_dir,"/df_coloc.RDS"))
saveRDS(df_mvcoloc, paste0(crohns_dir,"/df_mvcoloc.RDS"))

# Save eqtlgen - raw, all traits
saveRDS(df_msmr_eqtlgen, paste0(crohns_dir,"/eqtlgen_alltraits_raw.RDS"))

